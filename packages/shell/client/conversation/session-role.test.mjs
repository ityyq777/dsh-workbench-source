// 渲染真实选择器，通过按钮、角色事件和网络失败验证会话局部状态。
import assert from "node:assert/strict";
import Module, { createRequire } from "node:module";
import { React, createRenderer, all, textOf } from "../../../../scripts/helpers/test-react.mjs";
const require = createRequire(import.meta.url);
const load = Module._load;
Module._load = function (name, parent, main) {
  if (name === "react") return React;
  if (name === "react-dom") return { createPortal: (element) => element };
  return load.call(this, name, parent, main);
};
const { SessionRole, attachStream } = require("./session-role.cjs");
Module._load = load;
globalThis.document = { body: {} };
const state = { sessionId: "first", roleId: null, roles: [{ id: "tasks/publish", name: "发布者", domain: "tasks", description: "整理任务" }] };
const writes = [];
let failed = false;
globalThis.fetch = async (url, init) => {
  if (init) {
    const patch = JSON.parse(init.body);
    assert.equal(patch.sessionId, "first");
    writes.push(patch);
    if (failed) return { ok: false, json: async () => ({ error: "保存失败" }) };
    Object.assign(state, patch);
  } else assert.equal(url, "/workbench/api/session-role?sessionId=first");
  return { ok: true, json: async () => ({ ...state }) };
};
const events = {};
attachStream({ addEventListener(name, fn) { events[name] = fn; } });
const ensureStream = () => {};
const t = (key) => key;
const props = { sessionId: "first", ensureStream, t };
assert.equal(createRenderer()(SessionRole, { ...props, sessionId: null }), null);
const render = createRenderer();
const tick = () => new Promise((resolve) => setImmediate(resolve));
const tree = () => [render(SessionRole, props)].flat(Infinity).filter(Boolean).flatMap(all);
const trigger = () => tree().find((n) => n.props?.["aria-haspopup"] === "dialog");
const open = () => trigger().props.onClick();
const button = (name) => tree().find((n) => n.type === "button" && textOf(n).includes(name) && !n.props["aria-haspopup"]);
trigger(); await tick();
assert.equal(textOf(trigger()), "role_none");
assert.deepEqual(writes, []);
open(); await tick();
await button("发布者").props.onClick(); await tick();
assert.deepEqual(writes.at(-1), { sessionId: "first", roleId: "tasks/publish" });
assert.equal(textOf(trigger()), "发布者");
state.roles[0].name = "发布助手";
events["session-role"]({ data: JSON.stringify({ sessionId: "first" }) }); await tick();
assert.equal(textOf(trigger()), "发布助手");
assert.deepEqual(Object.keys(events).sort(), ["domains-changed", "open", "role-catalog", "session-role"]);
open(); await tick(); failed = true;
await button("role_none").props.onClick();
assert.ok(tree().some((node) => node.props?.role === "alert"));
failed = false; await button("role_none").props.onClick(); await tick();
assert.equal(textOf(trigger()), "role_none");
console.log("会话角色选择器交互通过：默认只读、绑定真实会话、角色事件、失败重试和取消角色");
