/** Isolated SQLite, registered real actions; never writes the installed workbench. */
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { setup } from '../packages/addons/tasks/lib/index.js';
import { timelines } from '../packages/addons/tasks/lib/timeline/task-timelines.js';
const db = new DatabaseSync(':memory:'), actions = new Map(), events = [];
db.exec('CREATE TABLE sync_change_log(table_name TEXT,row_id TEXT,op TEXT,payload TEXT,origin TEXT,updated_at INTEGER)');
const stamp = Date.parse('2024-01-03T12:00:00Z');
setup({db,addon:{version:'test'},now:()=>stamp,log(){},emit:(...event)=>events.push(event),hasDomain:()=>false,action:(n,a)=>actions.set(n,a)});
const call=(n,args={})=>actions.get(n).execute(args,{origin:'test'});
const create=args=>call('tasks.create',{tableId:'line-table',publishDate:'2024-01-01',targetDate:'2099-01-01',...args}).task;
const list=args=>call('tasks.timelines',args);
const members=(key,args={})=>call('tasks.timeline',{timelineKey:key,...args});
const totalChanges=()=>db.prepare('SELECT total_changes() n').get().n;
try {
  db.exec("INSERT INTO task_node(id,name,type,parent_id,path,created_at,updated_at) VALUES('line-table','Lines','1','1','/1/',0,0)");
  assert.deepEqual(list(),{records:[],total:0,current:1,size:20});
  for(const [id,title] of [['alpha','Alpha %_'],['beta','Beta']]) call('taskTimelines.create',{id,title});
  const a=create({source:1,timelineId:'alpha',title:'Alpha %_'}), b=create({source:1,timelineId:'beta',title:'Beta'});
  assert.equal(list().total,0,'singletons hidden');
  assert.equal(list({includeSingletons:true}).total,2);
  const a2=create({source:1,timelineKey:a.timelineKey,title:'Later unmatched',publishDate:'2024-01-02',status:2,doneDate:'2024-02-01'});
  const a3=create({source:1,timelineKey:a.timelineKey,title:'Closed',status:1,shutdownDate:'2024-03-01'});
  const retired=create({source:1,timelineKey:a.timelineKey,title:'Retired',status:1,shutdownDate:'2024-01-02'});
  const replacement=create({source:2,restartKey:retired.id,title:'Replacement'});
  const deleted=create({source:1,timelineKey:a.timelineKey,title:'Deleted'});
  call('tasks.delete',{id:deleted.id});
  let line=list().records[0];
  assert.equal(line.timelineKey,a.timelineKey);
  assert.equal(line.title,'Alpha %_','entity title is authoritative');
  assert.equal(line.taskCount,4); assert.equal(line.openCount,2); assert.equal(line.doneCount,1);
  assert.equal(line.firstPublishDate,'2024-01-01'); assert.equal(line.lastActivityDate,'2024-03-01','activity includes shutdown but not future target');
  assert(!members(a.timelineKey).some(r=>r.id===retired.id || r.id===deleted.id));
  db.prepare("UPDATE task SET publish_date='2023-12-31' WHERE id=?").run(a.id);
  assert.equal(list({titleKey:'aLPHa %_'}).total,1);
  assert.equal(list({titleKey:'Later unmatched'}).total,0,'search only representative title');
  assert.equal(list({titleKey:"' OR 1=1 --"}).total,0);
  let queries=0;
  const wrapped={prepare(sql){queries++;assert.match(sql,/GROUP BY timeline_id/);return db.prepare(sql);}};
  assert.equal(timelines(wrapped,{}).total,1); assert.equal(queries,1,'single SQL, no per-line query');
  const before=totalChanges(); list(); assert.equal(totalChanges(),before,'read only');
  for(let i=0;i<23;i++) {call('taskTimelines.create',{id:'single-'+i,title:'Singleton '+i});create({source:1,timelineId:'single-'+i,title:'Singleton '+i});}
  const first=list({includeSingletons:true}), second=list({includeSingletons:true,pageNumber:2});
  assert.equal(first.records.length,20); assert.equal(first.total,25); assert.equal(second.total,25); assert.equal(second.records.length,5);
  assert.equal(new Set([...first.records,...second.records].map(r=>r.timelineKey)).size,25,'stable tie-breaker across pages');
  const beyond=list({includeSingletons:true,pageNumber:100}); assert.equal(beyond.total,25); assert.deepEqual(beyond.records,[]);
  assert.deepEqual(list({titleKey:'no matches',pageNumber:100}),{records:[],total:0,current:100,size:20});
  const all=members(a.timelineKey), page=members(a.timelineKey,{pageNumber:2,pageSize:2});
  assert.equal(page.total,all.length); assert.deepEqual(page.records,all.slice(2,4));
  assert.deepEqual(members(a.timelineKey,{pageNumber:100}).records,[]);
  // More than the old tasks.list maximum: whole-line merge must not miss members.
  for(let i=0;i<510;i++) create({source:1,timelineKey:b.timelineKey,title:'Beta member '+i});
  const bRetired=create({source:1,timelineKey:b.timelineKey,title:'Old beta',status:1,shutdownDate:'2024-01-02'});
  const bReplacement=create({source:2,restartKey:bRetired.id,title:'New beta'});
  call('tasks.delete',{id:bReplacement.id});
  const input={timelineKeys:[a.timelineKey,b.timelineKey],timelineKey:a.timelineKey};
  const beforeMerge=totalChanges(), preview=call('tasks.timelineRefactor',{...input,dryRun:true});
  assert.equal(preview.wouldUpdate,511); assert.equal(preview.total,515); assert.equal(preview.ids,undefined);
  assert.equal(totalChanges(),beforeMerge,'dryRun changes no rows');
  const beforeEvents=events.length;
  db.exec("CREATE TEMP TRIGGER fail_merge BEFORE UPDATE OF timeline_key ON task WHEN OLD.title='Beta member 10' BEGIN SELECT RAISE(ABORT,'test merge failure'); END");
  assert.throws(()=>call('tasks.timelineRefactor',input),/test merge failure/);
  assert.equal(events.length,beforeEvents,'failed transaction emits no updates');
  assert.equal(members(b.timelineKey).length,511,'failed transaction restores all members');
  db.exec('DROP TRIGGER fail_merge');
  const result=call('tasks.timelineRefactor',input);
  assert.equal(result.updated,preview.wouldUpdate); assert.equal(result.total,preview.total);
  assert.equal(members(a.timelineKey).length,preview.total); assert.deepEqual(members(b.timelineKey),[]);
  assert.equal(list({titleKey:'Alpha'}).records[0].taskCount,preview.total);
  assert.equal(db.prepare('SELECT timeline_key FROM task WHERE id=?').get(retired.id).timeline_key,a.timelineKey);
  assert.equal(db.prepare('SELECT timeline_key FROM task WHERE id=?').get(bRetired.id).timeline_key,b.timelineKey,'retired source row is not moved');
  assert.equal(db.prepare('SELECT timeline_key FROM task WHERE id=?').get(bReplacement.id).timeline_key,null,'deleted source detached');
  const same=call('tasks.timelineRefactor',{timelineKeys:[a.timelineKey],timelineKey:a.timelineKey,dryRun:true}); assert.equal(same.wouldUpdate,0);
  for(const bad of [{timelineKeys:[a.timelineKey,'missing'],timelineKey:a.timelineKey},{timelineKeys:[a.timelineKey],timelineKey:'outside'},{...input,ids:[a.id]}]) assert.throws(()=>call('tasks.timelineRefactor',bad));
  const oldPreview=call('tasks.timelineRefactor',{ids:[a2.id],timelineKey:a.timelineKey,dryRun:true});
  assert.equal(oldPreview.wouldUpdate,0); assert.deepEqual(oldPreview.ids,[a2.id]);
  for(const args of [{pageSize:0},{pageSize:201},{pageNumber:0},{pageNumber:1.5},{includeSingletons:'false'}]) assert.throws(()=>list(args));
  assert.equal(actions.get('tasks.timeline').input.properties.pageSize.default,20);
  assert(actions.get('tasks.timelineRefactor').input.properties.timelineKeys);
  console.log('TIMELINES PASS: real source=1/source=2/delete, one SQL, counts/activity, literal search, stable pagination, singleton toggle, 515-member full merge, dryRun and legacy contracts');
} finally { db.close(); }
