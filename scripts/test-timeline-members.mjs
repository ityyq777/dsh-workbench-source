import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const members=require('../packages/addons/tasks/client/timeline-members.cjs');
const copy=require('../packages/addons/tasks/client/copy.cjs');
let calls=0;
const api={async call(){calls++;return {ok:true,result:[]}}};
for(const timelineKey of [undefined,null,'','  ']) assert.deepEqual(await members(api,{id:'task',timelineKey}),[]);
assert.equal(calls,0,'unlinked task must not issue a request');
assert.deepEqual(await members(api,{id:'task',timelineKey:'linked'}),[]);
assert.equal(calls,1);
const single={async call(action,args){assert.equal(action,'tasks.timeline');return {ok:true,result:[{id:'task',timelineKey:args.timelineKey}]}}};
assert.deepEqual(await members(single,{id:'task',timelineKey:'task'}),[],'legacy self-id singleton is unlinked');
assert.equal((await members(single,{id:'task',timelineKey:'explicit-line'})).length,1,'non-self single member stays linked');
const multiple={async call(){return {ok:true,result:[{id:'task'},{id:'second'}]}}};
assert.equal((await members(multiple,{id:'task',timelineKey:'task'})).length,2,'real legacy multi-member timeline stays linked');
await assert.rejects(members({async call(){return {ok:false,error:'database failed'}}},{id:'task',timelineKey:'line'}),/database failed/);
await assert.rejects(members({async call(){throw Error('network failed')}},{id:'task',timelineKey:'line'}),/network failed/);
assert.equal(copy.zh.noTimeline,'没有关联时间线');
assert.equal(copy.en.noTimeline,'No associated timeline');
console.log('TIMELINE ASSOCIATION PASS: empty keys, empty result, legacy self singleton, explicit singleton, multi-member, response/network errors, bilingual empty state');
