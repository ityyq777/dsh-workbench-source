import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const members=require('../packages/addons/tasks/client/timeline-members.cjs');
let calls=0;
const api={async call(){calls++;return {ok:true,result:[]}}};
for(const timelineId of [undefined,null,'']) assert.deepEqual(await members(api,{id:'task',timelineId,timelineKey:'legacy-self'}),[]);
assert.equal(calls,0,'legacy key cannot establish entity membership');
assert.deepEqual(await members(api,{id:'task',timelineId:'linked'}),[]);
assert.equal(calls,1);
const single={async call(action,args){assert.equal(action,'tasks.timeline'); assert.equal(args.timelineId,'task'); return {ok:true,result:[{id:'task'}]}}};
assert.equal((await members(single,{id:'task',timelineId:'task'})).length,1,'explicit self-id singleton remains linked');
assert.deepEqual(await members({async call(){return {ok:true,result:{records:[{id:'a'}]}}}},{timelineId:'line'}),[{id:'a'}]);
await assert.rejects(members({async call(){return {ok:false,error:'database failed'}}},{timelineId:'line'}),/database failed/);
await assert.rejects(members({async call(){throw Error('network failed')}},{timelineId:'line'}),/network failed/);
console.log('TIMELINE ENTITY MEMBERS PASS: no legacy inference, explicit singleton, empty entity, paged data, errors');
